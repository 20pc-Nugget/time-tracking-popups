#!/usr/bin/env python3
"""Generates TimeTrackingPopupsConfig.java.

RuneLite config interfaces are static, so the long list of per-patch toggles is generated from the
same two sources the plugin uses at runtime: Category.java (the groups) and FarmingWorld.java
(Time Tracking's patch table). The label/key rules here mirror PatchCatalog.java.

    python3 tools/generate_config.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src/main/java/com/timetrackingpopups"

TYPE_NAMES = {
    "MUSHROOM": "Mushroom", "BELLADONNA": "Belladonna", "ANIMA": "Anima", "HESPORI": "Hespori",
    "CELASTRUS": "Celastrus", "CRYSTAL_TREE": "Crystal tree", "HARDWOOD_TREE": "Hardwood",
    "REDWOOD": "Redwood", "COMPOST": "Compost bin", "BIG_COMPOST": "Giant compost bin",
}

BIRD_HOUSES = ["Mushroom Meadow (North)", "Mushroom Meadow (South)",
               "Verdant Valley (Northeast)", "Verdant Valley (Southwest)"]


def slug(label):
    return re.sub(r"[^a-z0-9]", "", label.lower())


def parse_categories():
    text = (PKG / "Category.java").read_text()
    body = text[text.index("{"):text.index(";\n\n\t/** Config key prefix")]
    cats = []
    pattern = re.compile(
        r'(\w+)\("(\w+)", "([^"]+)", "([^"]+)", (true|false), "\w+", PopupTier\.\w+, 0x[0-9A-Fa-f]+, '
        r'ItemID\.\w+, (true|false)(?:,\s*((?:PatchImplementation\.\w+(?:,\s*)?)+))?\)')
    for m in pattern.finditer(body):
        impls = re.findall(r"PatchImplementation\.(\w+)", m.group(7) or "")
        cats.append(dict(const=m.group(1), id=m.group(2), name=m.group(3), popup=m.group(4),
                         default=m.group(5) == "true", mixed=m.group(6) == "true", impls=impls))
    return cats


def parse_patches():
    text = (PKG / "data/FarmingWorld.java").read_text()
    out = []
    for rm in re.finditer(r'new FarmingRegion\("([^"]+)", (\d+), (?:true|false),', text):
        start = rm.end()
        # patches run until the region's own closing parenthesis, which is the first ")" that is
        # followed by whitespace and then "{", "," or ";" at the same nesting level
        depth, i = 1, start
        while depth:
            c = text[i]
            depth += (c == "(") - (c == ")")
            i += 1
        body = text[start:i]
        for pm in re.finditer(r'new FarmingPatch\("([^"]*)", VarbitID\.\w+, PatchImplementation\.(\w+)', body):
            out.append((rm.group(1), pm.group(1), pm.group(2)))
    return out


def label_for(cat, region, patch_name, impl):
    where = region + ("" if not patch_name else " " + patch_name)
    if not cat["mixed"]:
        return where
    type_name = TYPE_NAMES.get(impl, impl)
    if patch_name.lower() == type_name.lower():
        where = region
    return f"{type_name} ({where})"


def java_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def camel(key):
    head, _, rest = key.partition("_")
    return head + (rest[:1].upper() + rest[1:] if rest else "")


